// Writes supabase/multiplayer/003_courts.sql: every court's bricks in the
// game's own order, and the soonest a run could possibly have cleared it,
// so the server can check multiplayer scores brick by brick and pace.
//
//     node scripts/mp_courts.mjs
//
// Run it again whenever js/levels.js or js/game.js change (tests/mp_server_test.mjs
// fails if the bricks and the levels disagree). It takes a few minutes.
//
// "Soonest" comes from a bot far beyond any player: it never misses, never
// loses a ball, and has nine balls and Smash on from the first serve to the
// last brick. Its best time over several serves is each court's fastest; a
// court it could not clear within 90 s takes the fastest time of any court
// with at least as many bricks. reach = all those times up to and including
// this court, plus the win flourish and countdown between courts.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { LEVELS } from '../js/levels.js';
import { Game, MAX_BALLS } from '../js/game.js';

const GAP = 1.2 + 2.25; // js/main.js: the win flourish (S.ending) and the countdown (3 beats)
const SERVES = 6;
const DT = 1 / 120;

export const courtBricks = () => LEVELS.map((lv) => lv.rows.join('').replace(/[^TLHS]/g, ''));

function seeded(seed) {
  let s = seed >>> 0;
  return () => (s = (s * 1664525 + 1013904223) >>> 0) / 4294967296;
}

// Seconds for the bot to clear court i (Infinity if it cannot within 90 s).
export function botClear(i, seed, onBreak = () => {}) {
  let t = 0;
  const g = new Game(LEVELS[i], (e, ...a) => e === 'break' && onBreak(t, g, ...a), seeded(seed));
  while (t < 90 && g.state !== 'won') {
    if (g.state === 'serve' && g.ready) g.launch();
    if (g.state === 'play') {
      g.fx.smash = 7;
      if (g.balls.length < MAX_BALLS) g.applyTool('multiball');
      g.shield = true;
    }
    const low = g.balls.filter((q) => q.vy > 0).sort((p, q) => q.y - p.y)[0];
    if (low) g.movePaddleTo(low.x);
    g.update(DT);
    t += DT;
  }
  return g.state === 'won' ? t : Infinity;
}

export function courtReach() {
  const best = LEVELS.map((_, i) => Math.min(...Array.from({ length: SERVES }, (_, s) => botClear(i, 1000 * s + i))));
  const n = LEVELS.map((l) => l.blocks);
  const fast = best.map((t, i) => (isFinite(t) ? t : Math.min(...best.filter((u, j) => isFinite(u) && n[j] >= n[i]))));
  let clock = 0;
  return fast.map((t, i) => {
    clock += t + (i ? GAP : 0);
    return Math.floor(clock * 10) / 10; // rounded down: never stricter than measured
  });
}

export function courtsSql(reach = courtReach()) {
  const rows = courtBricks().map((b, i) => `  (${i + 1}, '${b}', ${reach[i].toFixed(1)})`);
  return `-- The Court: every court's bricks, in the order the game builds them
-- (js/game.js buildBlocks: row by row, left to right), and reach: the soonest
-- (seconds after the match starts) a run could have cleared that court, timed
-- by a bot beyond any player (scripts/mp_courts.mjs). Used by mp_checkpoint
-- to check multiplayer scores. DEVELOPMENT project only.
--
-- GENERATED by scripts/mp_courts.mjs from js/levels.js. Do not edit by hand.

insert into public.multiplayer_courts (court, bricks, reach) values
${rows.join(',\n')}
on conflict (court) do update set bricks = excluded.bricks, reach = excluded.reach;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = new URL('../supabase/multiplayer/003_courts.sql', import.meta.url);
  writeFileSync(out, courtsSql());
  console.log('Wrote', fileURLToPath(out), '-', LEVELS.length, 'courts');
}
